/**
 * 更新历史 —— 面向**客户**的「这周我们改了什么」。
 *
 * 🔴 **绝不要从 git commit 自动生成。**
 * commit 信息是写给自己看的:里面有收入数字、用户邮箱、「唯一付费客户扣款失败」
 * 这类东西,还有一堆客户根本不关心的内部实现。自动同步一次就会把它们公开出去,
 * 而且**收不回来**(页面会被爬、被缓存)。这份清单必须一条条手写、手筛。
 *
 * 写的时候只回答一个问题:**「这条对用户意味着什么?」**
 *   ✅「测距的距离数字挪到了线段中间，不再被端点挡住」
 *   ❌「修复 coords[floor(len/2)] 对两点线段取到终点的问题」
 *
 * 🌍 **五种语言全都要写**(zh / en / fr / ru / ar)。
 * 我一度只维护 zh+en、其余回落英文,理由是"维护成本"—— 那是**我替 owner 做的取舍,
 * 不该我做**(他的原话:「所有语言都要支持啊 别只做中文和英文」)。站点卖给的是
 * 迪拜的国际买家:俄语和阿拉伯语是这个市场的主力语言,把他们回落成英文,
 * 等于对最重要的两批客户说「这页不是给你看的」。
 * 加一条 = 写五行,不省。
 *
 * 加一条 = 在数组**开头**插一项。日期用发布日(YYYY-MM-DD)。
 */

export type ChangeKind = 'new' | 'improve' | 'fix'

/**
 * 这条更新是给谁看的。
 *   （省略）  所有人 —— 买家、经纪都会碰到的东西（地图、成交数据、账号…）
 *   'agent'  只有经纪/经纪公司/开发商用得到（带看、报价单、楼书解析、CRM…）
 *
 * 买家看到「实时带看的工具条重做了」只会觉得吵 —— 那是他碰不到的东西。
 * 判据只有一个：**一个纯买家账号能不能碰到这个改动?** 碰不到就是 'agent'。
 */
export type ChangeAudience = 'agent'
export type ChangeLang = 'zh' | 'en' | 'fr' | 'ru' | 'ar'

export interface ChangeEntry {
  date: string          // YYYY-MM-DD
  kind: ChangeKind
  /** 省略 = 所有人可见；'agent' = 只给经纪侧看（见 ChangeAudience） */
  audience?: ChangeAudience
  zh: string
  en: string
  fr: string
  ru: string
  ar: string
}

/**
 * i18n 语言码 → 这份数据里的字段。认不出的语言回落英文
 * (回落**只用于兜底**,不是省事的借口 —— 五种语言每条都必须写全)。
 */
export function pickLang(lng: string | undefined): ChangeLang {
  const l = (lng || 'en').toLowerCase()
  if (l.startsWith('zh')) return 'zh'
  if (l.startsWith('fr')) return 'fr'
  if (l.startsWith('ru')) return 'ru'
  if (l.startsWith('ar')) return 'ar'
  return 'en'
}

