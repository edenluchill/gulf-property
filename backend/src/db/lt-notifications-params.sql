-- 通知的**渲染参数** —— 让文案在前端按经纪的界面语言出。
--
-- 🔴 原来 title/body 是在写入那一刻拼成**中文成品**存进库的。
--    结果:一个英文界面的经纪,工作台上四条通知全是
--    「有人点了「联系经纪」」「有人看完了《为 陈先生 精选的 2 个家》」。
--    这和客户报告中英混杂是同一个病 —— 只不过那边漏在提示词,这边漏在数据库。
--
-- 语言在**渲染时**才知道才对:同一条通知,中文经纪看中文,英文经纪看英文;
-- 他换语言,历史通知也跟着换。写入时定死就永远做不到。
--
-- params 形如 {"who":"陈先生","known":true,"tour":"…","project":"…"}
-- title/body 仍然照写(旧客户端 / 以后可能的邮件模板兜底)。
-- params IS NULL 的历史行前端回落显示存着的中文 —— 全库只有 7 行,不值得回填。
ALTER TABLE lt_notifications ADD COLUMN IF NOT EXISTS params jsonb;
